const dictionaries: Record<Locale, Dict> = { en, zh }

export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  const dict = dictionaries[locale] ?? en
  let value = dict[key] ?? en[key] ?? key
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replaceAll(`{${name}}`, String(replacement))
    }
  }
  return value
}

/** Exposed for tests / debugging: every locale must have the same key set. */
export function dictionaryKeys(locale: Locale): string[] {
  return Object.keys(dictionaries[locale] ?? {})
}

export function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en'
  const languages = [...(navigator.languages ?? []), navigator.language ?? '']
  return languages.some((lang) => lang.toLowerCase().startsWith('zh')) ? 'zh' : 'en'
}
